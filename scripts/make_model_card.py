import json
from pathlib import Path

import pandas as pd

if __name__ == "__main__":
    p = Path("reports/metrics.csv")
    if not p.exists():
        raise SystemExit("Run training first")

    df = pd.read_csv(p)
    metrics_json = Path("reports/metrics.json")
    metadata = json.loads(metrics_json.read_text(encoding="utf-8")) if metrics_json.exists() else {}
    lines = [
        "# Model Card — Gym Churn Prediction",
        "",
        f"Application version: {metadata.get('app_version', 'unknown')}",
        "",
        f"Dataset kind: {metadata.get('dataset_kind', 'unknown')}",
        f"Label rule: {metadata.get('label_rule', 'unknown')}",
        "",
        metadata.get("evaluation_method", "Evaluation method not recorded."),
        "",
        (
            "The API score is uncalibrated. This is not evidence of real retention effects or a "
            "production-ready churn system. The bundled dataset is generated by this repository; "
            "no separate data license is stated."
        ),
        "",
        "| Model | Accuracy | F1 | ROC-AUC |",
        "|---|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        lines.append(f"| {r['model']} | {r['accuracy']:.4f} | {r['f1']:.4f} | {r['roc_auc']:.4f} |")

    Path("reports/model_card.md").write_text("\n".join(lines), encoding="utf-8")
    print("written reports/model_card.md")
